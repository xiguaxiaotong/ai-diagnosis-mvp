def seed(reset: bool = False) -> None:
    init_db()
    CASES_DIR.mkdir(parents=True, exist_ok=True)
    db = SessionLocal()
    try:
        if reset:
            for case in db.query(Case).all():
                case_service.delete_case(db, case.id)
            print("[reset] 已清空全部案例")

        existing = {c.title for c in db.query(Case).all()}
        ok, skipped, failed = 0, 0, 0
        for i, (title, industry, body) in enumerate(CASES, 1):
            if title in existing:
                print(f"[{i:>2}/20] 跳过（已入库）：{title}")
                skipped += 1
                continue
            path = CASES_DIR / f"case_{i:02d}.md"
            path.write_text(f"# {title}\n\n{body}", encoding="utf-8")
            try:
                case = case_service.create_case_from_file(db, path, title,
                                                          industry=industry)
                print(f"[{i:>2}/20] 入库 OK：id={case.id} {title}")
                ok += 1
            except Exception as e:
                failed += 1
                print(f"[{i:>2}/20] 失败：{title} → {e}")
        print(f"\n完成：新入库 {ok}，跳过 {skipped}，失败 {failed}，"
              f"案例库共 {db.query(Case).count()} 条")
    finally:
        db.close()


if __name__ == "__main__":
    seed(reset="--reset" in sys.argv)
